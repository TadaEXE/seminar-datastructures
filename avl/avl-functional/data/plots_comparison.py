# OCaml uses latency1 4_000_000 -> divide to get per-op time
OCAML_REPS = 4_000_000

# read C++ results from file
def read_cpp_results(path):
    data = {}
    with open(path) as f:
        for line in f:
            line = line.strip().rstrip(',')
            m = re.match(r'"([^"]+)":\[(.*)\]', line)
            if m:
                name = m.group(1)
                tuples = re.findall(r'\(([^)]+)\)', m.group(2))
                data[name] = [float(t.split(',')[0]) for t in tuples]
    return data

cpp_data = read_cpp_results(os.path.join(SCRIPT_DIR, '../../avl-imperative/results_comp_cpp.txt'))

# average 5 reps, skip zeros (OCaml sometimes has 0.0 as failed measurement)
def avg(values):
    vals = [v for v in values if v > 0]
    return sum(vals) / len(vals) if vals else 0

depths = list(range(15, 35))

# normalize OCaml to nanoseconds per operation
ocaml_i_opt   = [avg([v[0] for v in ocaml_data[f"i_opt_{n}"]]) / OCAML_REPS * 1e9 for n in depths]
ocaml_i_worst = [avg([v[0] for v in ocaml_data[f"i_worst_{n}"]]) / OCAML_REPS * 1e9 for n in depths]
ocaml_d_opt   = [avg([v[0] for v in ocaml_data[f"d_opt{n}"]]) / OCAML_REPS * 1e9 for n in depths]
ocaml_d_worst = [avg([v[0] for v in ocaml_data[f"d_worst{n}"]]) / OCAML_REPS * 1e9 for n in depths]

# C++ already in seconds per operation -> convert to nanoseconds
cpp_i_opt   = [avg(cpp_data[f"i_opt_{n}"]) * 1e9 for n in depths]
cpp_i_worst = [avg(cpp_data[f"i_worst_{n}"]) * 1e9 for n in depths]
cpp_d_opt   = [avg(cpp_data[f"d_opt{n}"]) * 1e9 for n in depths]
cpp_d_worst = [avg(cpp_data[f"d_worst{n}"]) * 1e9 for n in depths]

# --- plot ---
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))
fig.suptitle("OCaml functional vs C++ imperative AVL tree")

ax1.set_title("Idepthsert: best vs worst case")
ax1.plot(depths, ocaml_i_opt,   "r--", label="OCaml best")
ax1.plot(depths, ocaml_i_worst, "b--", label="OCaml worst")
ax1.plot(depths, cpp_i_opt,     "r-",  label="C++ best")
ax1.plot(depths, cpp_i_worst,   "b-",  label="C++ worst")
ax1.set_xlabel("tree depth (n)")
ax1.set_ylabel("time per operation (depths)")
ax1.legend()

ax2.set_title("Delete: best vs worst case")
ax2.plot(depths, ocaml_d_opt,   "r--", label="OCaml best")
ax2.plot(depths, ocaml_d_worst, "b--", label="OCaml worst")
ax2.plot(depths, cpp_d_opt,     "r-",  label="C++ best")
ax2.plot(depths, cpp_d_worst,   "b-",  label="C++ worst")
ax2.set_xlabel("tree depth (n)")
ax2.set_ylabel("time per operation (depths)")
ax2.legend()

plt.tight_layout()
plt.show()
